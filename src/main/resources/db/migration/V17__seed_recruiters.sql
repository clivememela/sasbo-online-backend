-- Populates the `recruiters` table with the SASBO organiser list and the
-- other recruitment types, each keyed by its recruitment number. Columns:
--   name, members_recruited, region, area_code  (region/area_code optional)
--
-- The table is normally created by Hibernate (ddl-auto=update). The
-- CREATE TABLE IF NOT EXISTS below guarantees it also exists on a fresh
-- database, where Flyway runs BEFORE Hibernate schema generation.
--
-- Idempotent: rows are inserted only when the table is empty, so this
-- migration coexists with DataSeeder (which also seeds recruiters only
-- when the count is 0) without producing duplicates. The surrogate id is
-- left to the identity column, keeping the sequence in sync for JPA inserts.
-- ============================================================

