-- ============================================================
-- Add description column to representative_roles so each role
-- can carry a human-readable explanation (e.g. "Branch executive
-- committee member") displayed in the frontend dropdown.
--
-- The table is normally created by Hibernate (ddl-auto=update). The
-- CREATE TABLE IF NOT EXISTS below guarantees it also exists on a fresh
-- database, where Flyway runs BEFORE Hibernate schema generation.
-- ============================================================

CREATE TABLE IF NOT EXISTS representative_roles (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name          VARCHAR(255) NOT NULL UNIQUE,
    description        VARCHAR(500),
    requires_structure BOOLEAN DEFAULT FALSE,
    is_elected_role    BOOLEAN DEFAULT FALSE
);

ALTER TABLE representative_roles ADD COLUMN IF NOT EXISTS description VARCHAR(500);
