-- ----------------------------------------------------------------------------
-- Union structures and representative roles
--
-- Both are created HERE rather than where they look like they belong, and the
-- ordering is not a matter of taste:
--
--   * V2 adds foreign keys from members.structure_id and members.role_id to
--     these two tables. V2 is the FIRST migration. So both tables must already
--     exist, or V2 fails.
--   * V4 also has CREATE TABLE IF NOT EXISTS union_structures and V7 has
--     CREATE TABLE IF NOT EXISTS representative_roles. Both become no-ops
--     against this baseline -- which is exactly why they were written with
--     IF NOT EXISTS. They are not dead code; they are what let the same
--     migrations run against the ddl-auto databases already in the field.
--
-- The identity columns matter as much as the tables: V14 and V16 both do
-- ALTER SEQUENCE union_structures_id_seq / representative_roles_id_seq, which
-- are the sequence names an identity (or serial) column on `id` produces. A
-- plain INTEGER PRIMARY KEY here would fail those migrations at V14.
--
-- Columns deliberately absent: union_structures.parent_id (added V14),
-- union_structures.requires_election_date (added V16),
-- representative_roles.description (added V7).
-- ----------------------------------------------------------------------------

CREATE TABLE union_structures (
