-- Members
--
-- Columns deliberately absent (each is added by a later migration, and adding
-- it here would make that migration a silent no-op):
--   V2  is_representative, role_id, structure_id, election_date
--   V3  personal_email, work_email, preferred_email
--   V4  recruitment_representative_id, area_id
--   V15 date_of_birth
--
-- Two columns below outlive the entity that created them. Neither is mapped by
-- any Java field today, and both are intentional:
--
--   recruitment_rep
--     The original member-to-member recruitment link. V2 puts a self
--     foreign key AND a CHECK constraint on it, so it cannot be omitted here
--     without breaking V2 -- and no migration ever drops it, so it survives to
--     the end of the chain unmapped. Hibernate `validate` ignores columns the
--     model does not mention, so it is harmless; it is simply dead. Leave it.
--     Anyone dropping it must delete V2's fk_member_recruiter_self and
--     chk_cannot_recruit_self in the same change.
--
--   job_grade
--     A free-text job grade, replaced by the job_grade_id foreign key to
--     job_grades. V11 runs ALTER TABLE members ALTER COLUMN job_grade TYPE
--     VARCHAR(255) -- which has no IF EXISTS and therefore FAILS OUTRIGHT if
--     the column is missing. So it must be created here even though nothing
--     reads it. It ends the chain vestigial, exactly like recruitment_rep.
--     V11 becomes a no-op type change against this baseline (the column is
--     already VARCHAR(255)); it still does real work on the ddl-auto databases
--     in the field, where the column may be numeric.
--
-- The seven columns after job_grade are dropped again by V8. They are here so
-- that V8 does what it says it does: on a database built only from these
-- migrations, a V8 that dropped nothing would be indistinguishable from a V8
-- that was never applied. Their exact types are inferred -- nothing depends on
-- them, because they do not survive the chain.
-- ----------------------------------------------------------------------------

