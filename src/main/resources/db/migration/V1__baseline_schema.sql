-- ----------------------------------------------------------------------------
-- Representatives
--
-- Columns deliberately absent:
--   V4  member_id, area_id, rep_role, structure_id, election_date
--   V12 personal_email, work_email, preferred_email
--   V13 is_elected_rep
--
-- `name` is here and NOT NULL because V9 drops it and explains why: the entity
-- was split into first_names + surname, but ddl-auto never drops a column, so
-- the original NOT NULL column stayed behind and broke every INSERT. That is
-- the defect V9 fixes, and it can only be reproduced if the column exists.
--
-- role_id is here rather than in a later migration because no migration ever
-- adds it -- the entity gained the association while ddl-auto was still
-- creating columns, so nothing was ever written down. Without it the chain
-- cannot satisfy `validate` at the end.
-- ----------------------------------------------------------------------------

CREATE TABLE representatives (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,
    first_names VARCHAR(255),
    surname     VARCHAR(255),
    phone       VARCHAR(255),
    role_id     INTEGER,
    CONSTRAINT fk6yliib1dixmbgqkychgadwwmi FOREIGN KEY (role_id) REFERENCES representative_roles (id)
);
