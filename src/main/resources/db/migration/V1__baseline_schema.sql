-- ============================================================================
-- V1: Baseline schema
--
-- WHAT THIS IS
--   The schema as it stood BEFORE V2 ran -- i.e. the shape every later
--   migration expects to find. It is NOT today's entity model. Columns that
--   V2-V18 add are deliberately absent here, and columns that V2-V18 drop are
--   deliberately present.
--
-- WHY IT EXISTS
--   This database was created by Hibernate `ddl-auto: update`, not by
--   migrations, so V2 was the first migration ever written and it ALTERs
--   tables nobody had created in SQL. Without this file the chain cannot run
--   against an empty database at all: V2 fails on its first statement.
--
-- HOW IT WAS RECONSTRUCTED
--   By generating the schema Hibernate produces from the current entity model,
--   then reversing every V2-V18 delta. It is therefore an inference, not a
--   transcript -- no dump of the original database exists. The judge of
--   correctness is Hibernate `ddl-auto: validate` at the END of the chain, not
--   a human reading this file.
--
-- THE GAP AT V6 IS DELIBERATE
--   There is no V6__*.sql and there never was one; the version was skipped
--   when the migration was abandoned before it was committed. Flyway does not
--   require contiguous versions. Do NOT fabricate a V6 to "fill" it -- an
--   empty migration at that version would be a lie about the history, and any
--   real V6 would change what V7 finds.
--
-- IF THIS FILE APPEARS TO NEED A CHANGE TO V2-V18
--   It does not. V2-V18 are the incumbent history and the only surviving
--   evidence of the original schema. Editing one to make this file work
--   destroys that evidence and silently diverges this database from every
--   database already in the field. Fix V1 instead.
-- ============================================================================


