/**
 * The demonstration population (the October build, demo-data): invented members in every region's areas, so that no
 * figure of month end reads nought on a demonstration -- every pack with members, joiners and leavers in each of the
 * three months before the clock's, the suspended under every suspension code of Stephne's sheet, leavers under every
 * deletion code. Generated by {@code DemonstrationPopulationGenerator} in the test sources, committed as
 * {@value #SEED_FILE}; the contract other seeders build on is {@code contracts/demo-population.md}.
 *
 * <h2>The locks, as the invented members' (MD53)</h2>
 * Never where the production marker is set, and only where the switch says {@code all}: the members stand at SASBO's
 * workplaces and are made from their staff numbers.
 *
 * <h2>When absent</h2>
 * Whichever members of the file are missing are put on record -- one query for the file's numbers, one JDBC batch,
 * because IDENTITY ids make {@code saveAll} a round trip a row (MD44), each member Active as captured -- and each
 * member's past is written once, at the first start that can, keyed by the member and the actor
 * {@value DemonstrationMemberSeeder#SEED_ACTOR}. A tester's member is never touched. The past goes through
 * {@code MemberService.changeStatus}, the one writer of a member's status (03.4, MemberStatusWritersTest): from, to,
 * reason, SASBO's code, who and when -- so every figure, the history and ACB read it as any change; none of it is ACB's
 * {@code SUBS_IN_ARREARS} or {@code UNPAID_SUSPENDED}. About a hundred and thirty changes, a few statements each.
 *
 * <h2>Dated by the clock</h2>
 * A joiner and every change fall in the month {@code monthsBack} before the clock's month at the start that writes
 * them, so the demonstration never goes stale and the clock's own month stays free for a live demonstration and the
 * suite.
 */
@Slf4j
@Component
public class DemonstrationPopulationSeeder {

    /** The generated population, numbered downwards from M-098500 (the contract's block). */
    public static final String SEED_FILE = "data/demonstration_population.json";

    private final NamedParameterJdbcTemplate jdbc;
    private final TransactionTemplate transactions;
    private final SasboEnvironment environment;
    private final WorkplaceSwitch workplaceSwitch;
    private final MemberService members;
    private final Clock clock;

    public DemonstrationPopulationSeeder(NamedParameterJdbcTemplate jdbc, PlatformTransactionManager transactionManager,
                                         SasboEnvironment environment, WorkplaceSwitch workplaceSwitch,
                                         MemberService members, Clock clock) {
        this.jdbc = jdbc;
        this.transactions = new TransactionTemplate(transactionManager);
        this.environment = environment;
        this.workplaceSwitch = workplaceSwitch;
        this.members = members;
        this.clock = clock;
    }

    /** @return how many rows this call wrote -- members, suspension codes and changes; nought on a second start */
    public int seed() throws IOException {
        if (environment.isProduction() || !workplaceSwitch.staffNumbersServed()) {
            return 0;
        }
        DemonstrationPopulation file = readSeedFile();
        Map<String, Long> onRecord = new HashMap<>();
        jdbc.query("SELECT id, membership_number FROM members WHERE membership_number IN (:numbers)",
                new MapSqlParameterSource("numbers", file.members().stream()
                        .map(DemonstrationPopulation.Member::membershipNumber).toList()),
                rs -> {
                    onRecord.put(rs.getString("membership_number"), rs.getLong("id"));
                });
        List<DemonstrationPopulation.Member> missing = file.members().stream()
                .filter(member -> !onRecord.containsKey(member.membershipNumber())).toList();
        Map<String, List<DemonstrationPopulation.Change>> pastOf = new LinkedHashMap<>();
        file.past().forEach(change -> pastOf.computeIfAbsent(change.membershipNumber(), n -> new ArrayList<>()).add(change));

        // Of the members already on record, those whose past the seed has not written yet. A member put on record by
        // this call has none, so the question is asked only of the others -- and on a second start it is the last.
        Set<Long> pastWritten = new HashSet<>();
        List<Long> askAbout = pastOf.keySet().stream().map(onRecord::get).filter(java.util.Objects::nonNull).toList();
        if (!askAbout.isEmpty()) {
            pastWritten.addAll(jdbc.queryForList("SELECT DISTINCT member_id FROM member_status_changes "
                    + "WHERE changed_by = :seed AND member_id IN (:ids)", new MapSqlParameterSource("seed",
                    DemonstrationMemberSeeder.SEED_ACTOR).addValue("ids", askAbout), Long.class));
        }
        boolean pastOutstanding = pastOf.keySet().stream()
                .anyMatch(number -> !onRecord.containsKey(number) || !pastWritten.contains(onRecord.get(number)));
        if (missing.isEmpty() && !pastOutstanding) {
            return 0;
        }

        long started = System.nanoTime();
        YearMonth now = MonthRange.current(clock);
        int[] written = new int[3];
        try {
            transactions.executeWithoutResult(status -> {
                written[0] = putOnRecord(missing, now, onRecord);
                written[1] = suspensionCodes(file);
                written[2] = past(pastOf, onRecord, pastWritten, now);
            });
        } catch (DataIntegrityViolationException seededMeanwhile) {
            log.info("The demonstration population was put on record by another instance starting at the same time");
            return 0;
        }
        long elapsed = (System.nanoTime() - started) / 1_000_000;
        log.info("Seeded {} demonstration member(s), {} suspension code(s) and {} change(s) of their past from {} in {} ms",
                written[0], written[1], written[2], SEED_FILE, elapsed);
        return written[0] + written[1] + written[2];
    }

    // ------------------------------------------------------------------------------------------------ the members

    /** The missing members, by one batch, each at its workplace; their ids added to {@code onRecord}. */
    private int putOnRecord(List<DemonstrationPopulation.Member> missing, YearMonth now, Map<String, Long> onRecord) {
        if (missing.isEmpty()) {
            return 0;
        }
        Map<Integer, Long> workplaces = new HashMap<>();
        jdbc.query("SELECT id, ra_number FROM workplaces WHERE ra_number IN (:ra)", new MapSqlParameterSource("ra",
                missing.stream().map(DemonstrationPopulation.Member::workplaceRaNumber).distinct().toList()), rs -> {
                    workplaces.put(rs.getInt("ra_number"), rs.getLong("id"));
                });
        Map<String, Long> committees = new HashMap<>();
        List<String> committeeCodes = missing.stream().map(DemonstrationPopulation.Member::becCommitteeCode)
                .filter(java.util.Objects::nonNull).distinct().toList();
        if (!committeeCodes.isEmpty()) {
            jdbc.query("SELECT id, code FROM committees WHERE code IN (:codes)",
                    new MapSqlParameterSource("codes", committeeCodes), rs -> {
                        committees.put(rs.getString("code"), rs.getLong("id"));
                    });
        }
        // A recruiter is named in the file by its POSITION, never its name -- the recruiters are SASBO's own staff.
        List<Long> recruiters = jdbc.queryForList("SELECT id FROM recruiters ORDER BY id", new MapSqlParameterSource(),
                Long.class);

        LocalDateTime stamped = LocalDateTime.ofInstant(clock.instant(), MonthRange.ZONE);
        List<MapSqlParameterSource> rows = new ArrayList<>();
        List<String> numbers = new ArrayList<>();
        int withoutWorkplace = 0;
        for (DemonstrationPopulation.Member member : missing) {
            Long workplace = workplaces.get(member.workplaceRaNumber());
            if (workplace == null) {
                withoutWorkplace++;
                continue;
            }
            LocalDate joined = joinDate(member, now);
            Long committee = member.becCommitteeCode() == null ? null : committees.get(member.becCommitteeCode());
            Long recruiter = member.recruiter() == null || recruiters.isEmpty() ? null
                    : recruiters.get((member.recruiter() - 1) % recruiters.size());
            rows.add(new MapSqlParameterSource()
                    .addValue("number", member.membershipNumber())
                    .addValue("employee", member.employeeNumber())
                    .addValue("title", member.title())
                    .addValue("initials", member.initials())
                    .addValue("firstNames", member.firstNames())
                    .addValue("surname", member.surname())
                    .addValue("identityType", member.identityType())
                    .addValue("identity", member.identityNumber())
                    .addValue("born", member.dateOfBirth())
                    .addValue("gender", member.gender())
                    .addValue("race", member.race())
                    .addValue("joined", joined)
                    .addValue("email", member.personalEmail())
                    .addValue("preferred", member.preferredEmail())
                    .addValue("phone", member.phone())
                    .addValue("address", member.address())
                    .addValue("branch", member.branch())
                    .addValue("bank", member.bankName())
                    .addValue("payment", member.paymentType())
                    .addValue("subscription", new BigDecimal(member.monthlySubscription()))
                    .addValue("frequency", member.subscriptionFrequency())
                    .addValue("lastChanged", member.joinsInThePast() ? joined : member.dateLastChanged())
                    .addValue("workplace", workplace)
                    .addValue("recruiter", recruiter, java.sql.Types.BIGINT)
                    .addValue("steward", member.shopSteward())
                    .addValue("elected", member.shopStewardElectionDate())
                    .addValue("bec", committee != null)
                    .addValue("committee", committee, java.sql.Types.BIGINT)
                    .addValue("memnet", member.memnet())
                    .addValue("stamped", stamped));
            numbers.add(member.membershipNumber());
        }
        if (withoutWorkplace > 0) {
            log.warn("{} demonstration member(s) of {} stand at a workplace that is not on record, and were left out",
                    withoutWorkplace, SEED_FILE);
        }
        if (rows.isEmpty()) {
            return 0;
        }
        // Everybody is put on record ACTIVE: their past moves them, as it would have moved them then.
        jdbc.batchUpdate("""
                INSERT INTO members (membership_number, employee_number, title, initials, first_names, surname,
                  identity_type, identity_number, date_of_birth, gender, race, status, join_date, personal_email,
                  preferred_email, phone, cell_tel, address, branch, bank_name, payment_type, monthly_subscription_numeric,
                  subscription_frequency, current_balance_numeric, arrears_balance_numeric, last_month_balance_numeric,
                  date_last_changed, is_representative, workplace_id, recruiter_id, is_shop_steward,
                  shop_steward_election_date, is_bec, bec_committee_id, is_memnet, created_at, updated_at)
                VALUES (:number, :employee, :title, :initials, :firstNames, :surname, :identityType, :identity, :born,
                  :gender, :race, 'Active', :joined, :email, :preferred, :phone, :phone, :address, :branch, :bank,
                  :payment, :subscription, :frequency, 0.00, 0.00, 0.00, :lastChanged, FALSE, :workplace, :recruiter,
                  :steward, :elected, :bec, :committee, :memnet, :stamped, :stamped)
                """, rows.toArray(MapSqlParameterSource[]::new));
        jdbc.query("SELECT id, membership_number FROM members WHERE membership_number IN (:numbers)",
                new MapSqlParameterSource("numbers", numbers), rs -> {
                    onRecord.put(rs.getString("membership_number"), rs.getLong("id"));
                });
        return rows.size();
    }

    /** A joiner of the three past months is dated by the clock; everyone else joined on the day the file states. */
    static LocalDate joinDate(DemonstrationPopulation.Member member, YearMonth now) {
        return member.joinsInThePast() ? now.minusMonths(member.joinedMonthsBack()).atDay(member.joinDay())
                : member.joinDate();
    }

    // ------------------------------------------------------------------------------------------------ the codes

    /**
     * The suspension codes of Stephne's sheet the members are suspended under that are not on record yet -- by code,
     * one query and one batch. The reference lists never delete a code they do not list (ListSync), and a list row that
     * later names the same code takes the name over, so nothing here fights them.
     */
    private int suspensionCodes(DemonstrationPopulation file) {
        if (file.suspensionCodes() == null || file.suspensionCodes().isEmpty()) {
            return 0;
        }
        Set<Integer> present = new HashSet<>(jdbc.queryForList("SELECT code FROM suspension_codes WHERE code IN (:codes)",
                new MapSqlParameterSource("codes", file.suspensionCodes().stream()
                        .map(DemonstrationPopulation.Code::code).toList()), Integer.class));
        MapSqlParameterSource[] absent = file.suspensionCodes().stream().filter(code -> !present.contains(code.code()))
                .map(code -> new MapSqlParameterSource("code", code.code()).addValue("name", code.name()))
                .toArray(MapSqlParameterSource[]::new);
        if (absent.length > 0) {
            jdbc.batchUpdate("INSERT INTO suspension_codes (code, name) VALUES (:code, :name)", absent);
        }
        return absent.length;
    }

    // ------------------------------------------------------------------------------------------------ the past

    /**
     * Each member's past not yet written -- all of a member's changes or none of them -- THROUGH THE REAL STATUS CHANGE
     * ({@code MemberService.changeStatus}, the one writer of a member's status, 03.4), with the actor
     * {@value DemonstrationMemberSeeder#SEED_ACTOR} and the change's own instant, as the invented members' past is
     * (03.7): so every figure, the history and ACB read it as any change. A change at a time, in the member's order.
     */
    private int past(Map<String, List<DemonstrationPopulation.Change>> pastOf, Map<String, Long> onRecord,
                     Set<Long> pastWritten, YearMonth now) {
        Codes codes = codes();
        int written = 0;
        int skipped = 0;
        for (Map.Entry<String, List<DemonstrationPopulation.Change>> member : pastOf.entrySet()) {
            Long id = onRecord.get(member.getKey());
            if (id == null || pastWritten.contains(id)) {
                continue;
            }
            List<DemonstrationPopulation.Change> changes = new ArrayList<>(member.getValue());
            changes.sort(Comparator.comparingInt((DemonstrationPopulation.Change c) -> -c.monthsBack())
                    .thenComparingInt(DemonstrationPopulation.Change::day));
            List<MemberService.StatusChange> his = new ArrayList<>();
            for (DemonstrationPopulation.Change change : changes) {
                Long deletion = change.deletionCode() == null ? null : codes.deletion(change.deletionCode(),
                        change.reasonUnderCode());
                Long suspension = change.suspensionCode() == null ? null : codes.suspension(change.suspensionCode());
                if ((change.deletionCode() != null && deletion == null)
                        || (change.suspensionCode() != null && suspension == null)) {
                    his = null;
                    break;
                }
                Instant at = now.minusMonths(change.monthsBack()).atDay(change.day()).atTime(10, 0)
                        .atZone(MonthRange.ZONE).toInstant();
                his.add(new MemberService.StatusChange(change.toStatus(), null,
                        MemberStatusReason.valueOf(change.reason()), deletion, suspension, null,
                        DemonstrationMemberSeeder.SEED_ACTOR, at));
            }
            if (his == null) {
                skipped++;
                continue;
            }
            for (MemberService.StatusChange change : his) {
                written += members.changeStatus(id.intValue(), change)
                        .map(outcome -> outcome.written() != null ? 1 : 0).orElse(0);
            }
        }
        if (skipped > 0) {
            log.warn("{} demonstration member(s) of {} have a past naming a code that is not on record; it is written at "
                    + "the next start that finds the code", skipped, SEED_FILE);
        }
        return written;
    }

    /** SASBO's codes on record, by their numbers -- and the reasons under a code, by name -- read once. */
    private Codes codes() {
        Map<Integer, Long> deletion = new HashMap<>();
        Map<String, Long> under = new HashMap<>();
        Map<Long, Integer> numberOf = new HashMap<>();
        List<Object[]> children = new ArrayList<>();
        jdbc.query("SELECT id, sasbo_code, name, parent_id FROM deletion_codes", rs -> {
            long id = rs.getLong("id");
            int number = rs.getInt("sasbo_code");
            boolean numbered = !rs.wasNull();
            long parent = rs.getLong("parent_id");
            boolean child = !rs.wasNull();
            if (numbered) {
                deletion.put(number, id);
                numberOf.put(id, number);
            } else if (child) {
                children.add(new Object[] {parent, rs.getString("name"), id});
            }
        });
        for (Object[] child : children) {
            Integer number = numberOf.get((Long) child[0]);
            if (number != null) {
                under.put(number + " " + child[1], (Long) child[2]);
            }
        }
        Map<Integer, Long> suspension = new HashMap<>();
        jdbc.query("SELECT id, code FROM suspension_codes", rs -> {
            suspension.put(rs.getInt("code"), rs.getLong("id"));
        });
        return new Codes(deletion, under, suspension);
    }

    /** The codes a past is written with. */
    private record Codes(Map<Integer, Long> deletion, Map<String, Long> under, Map<Integer, Long> suspension) {

        /** SASBO's numbered code -- or, where a reason under it is named, that reason's own row (04.5). */
        Long deletion(int number, String reasonUnder) {
            return reasonUnder == null ? deletion.get(number) : under.get(number + " " + reasonUnder);
        }

        Long suspension(int code) {
            return suspension.get(code);
        }
    }

    /** The file, read STRICTLY: a key the record does not declare fails the read, instead of losing a field (F65). */
    public static DemonstrationPopulation readSeedFile() throws IOException {
        JsonMapper strict = JsonMapper.builder()
                .findAndAddModules()
                .enable(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES)
                .build();
        try (InputStream stream = new ClassPathResource(SEED_FILE).getInputStream()) {
            return strict.readValue(stream, DemonstrationPopulation.class);
        }
    }
}
